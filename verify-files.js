const makeCore = // Shared logic (embedded into the generated verify script too)
  (module.exports = function makeCore(ts) {
    const K = ts.SyntaxKind;
    let skipImports = false;
    const sha = (s) =>
      require("crypto").createHash("sha1").update(s, "utf8").digest("hex");

    function dump(node) {
      if (
        node.kind === K.ParenthesizedExpression ||
        node.kind === K.ParenthesizedType
      )
        return dump(node.expression || node.type);
      if (
        ts.isIdentifier(node) ||
        ts.isStringLiteral(node) ||
        ts.isNoSubstitutionTemplateLiteral(node)
      )
        return "V:" + node.text;
      if (ts.isNumericLiteral(node)) return "N:" + node.text;
      if (node.kind === K.JsxText) {
        const t = node.text.replace(/\s+/g, " ").trim();
        return t ? "JT:" + t : "";
      }
      if (
        node.kind === K.JsxExpression &&
        node.expression &&
        ts.isStringLiteral(node.expression) &&
        node.expression.text.trim() === ""
      )
        return "";
      let extra = "";
      if (
        node.kind === K.PrefixUnaryExpression ||
        node.kind === K.PostfixUnaryExpression
      )
        extra = "#" + node.operator;
      if (node.kind === K.VariableDeclarationList)
        extra = "#" + (node.flags & (ts.NodeFlags.Let | ts.NodeFlags.Const));
      const kids = [];
      ts.forEachChild(node, (c) => {
        if (skipImports && c.kind === K.ImportDeclaration) return;
        const d = dump(c);
        if (d !== "") kids.push(d);
      });
      // template parts / token-only nodes carry text
      if (kids.length === 0 && typeof node.text === "string")
        extra += "=" + node.text;
      return K[node.kind] + extra + "(" + kids.join(",") + ")";
    }

    function parse(name, text) {
      const kind = name.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
      return ts.createSourceFile(
        name,
        text.replace(/^\uFEFF/, ""),
        ts.ScriptTarget.Latest,
        true,
        kind,
      );
    }

    function isUnit(n) {
      const p = n.parent;
      if (!p) return false;
      if (
        p.kind === K.SourceFile ||
        p.kind === K.Block ||
        p.kind === K.ModuleBlock ||
        p.kind === K.CaseClause ||
        p.kind === K.DefaultClause
      )
        return true;
      return (
        n.kind === K.JsxElement ||
        n.kind === K.JsxSelfClosingElement ||
        n.kind === K.JsxFragment
      );
    }

    function analyze(name, text) {
      const sf = parse(name, text);
      skipImports = false;
      const wholeAll = sha(dump(sf));
      skipImports = true;
      const whole = sha(dump(sf));
      const units = [];
      (function visit(n) {
        if (n.kind === K.ImportDeclaration) return;
        if (n.kind !== K.SourceFile && isUnit(n)) {
          const start = n.getStart(sf);
          units.push({
            fp: sha(dump(n)).slice(0, 8),
            line: sf.getLineAndCharacterOfPosition(start).line + 1,
            len: n.getEnd() - start,
            text: sf.text.slice(start, start + 120).replace(/\s+/g, " "),
          });
        }
        ts.forEachChild(n, visit);
      })(sf);
      skipImports = false;
      const syntaxErrors = (sf.parseDiagnostics || []).length;
      return { whole, wholeAll, units, syntaxErrors };
    }
    return { analyze };
  });
